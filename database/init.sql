-- Dijalankan PostgreSQL saat volume database baru pertama dibuat.
CREATE TABLE IF NOT EXISTS books (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL CHECK (length(trim(title)) > 0),
  author VARCHAR(100) NOT NULL CHECK (length(trim(author)) > 0),
  category VARCHAR(60) NOT NULL CHECK (length(trim(category)) > 0),
  year INTEGER NOT NULL CHECK (year BETWEEN 1900 AND 2100),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock BETWEEN 0 AND 1000000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
