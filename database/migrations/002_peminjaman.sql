-- Migrasi 002: peminjaman dan pengembalian buku (khusus PostgreSQL / mode SQL).
-- Aman dijalankan pada database yang sudah berisi data dan aman diulang (IF NOT EXISTS).
-- Hanya MENAMBAH tabel loans. Tabel books tidak diubah, dikosongkan, atau diisi ulang.
-- Terapkan ke database yang sedang berjalan dengan: ./scripts/migrasi.sh

CREATE TABLE IF NOT EXISTS loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Bila buku dihapus setelah semua pinjamannya selesai, riwayat tetap ada: book_id menjadi NULL, judul tetap di book_title.
  book_id INTEGER REFERENCES books(id) ON DELETE SET NULL,
  book_title VARCHAR(150) NOT NULL,
  borrower_name VARCHAR(100) NOT NULL CHECK (length(trim(borrower_name)) > 0),
  borrower_class VARCHAR(30) NOT NULL CHECK (length(trim(borrower_class)) > 0),
  -- NIM disimpan sebagai teks supaya angka nol di depan tidak hilang.
  borrower_nim VARCHAR(20) NOT NULL CHECK (borrower_nim ~ '^[0-9]{5,20}$'),
  loan_date DATE NOT NULL,
  due_date DATE NOT NULL,
  returned_date DATE,
  note VARCHAR(300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT loans_due_after_loan CHECK (due_date >= loan_date),
  CONSTRAINT loans_returned_after_loan CHECK (returned_date IS NULL OR returned_date >= loan_date)
);

-- Mempercepat pemeriksaan "apakah buku ini masih dipinjam" saat menghapus buku.
CREATE INDEX IF NOT EXISTS loans_active_book_idx ON loans (book_id) WHERE returned_date IS NULL;
